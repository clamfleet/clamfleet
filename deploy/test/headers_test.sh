# headers_test.sh - every tracked file carries both SPDX lines (CLAUDE.md, "Rules"), or is one of
# the listed exceptions below. `make check` runs it, so a contributor's new file without the
# header fails before review. It then proves the check itself can fail: a temporary repository
# with one good file, one bad file, and one file per exception.
#
# Only tracked files are checked (git ls-files): an untracked scratch file is not a finding, and
# a file added with `git add` is.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(cd "$here/../.." && pwd)"
LIC='SPDX-License-Identifier: AGPL-3.0-only'
COPY='SPDX-FileCopyrightText: The ClamFleet Authors'

# has_header FILE: both lines within the first 15 lines. A header further down is not a header:
# a file whose first lines are code or a shebang plus a long comment still fits in 15.
has_header() {
	local head
	head="$(head -n 15 -- "$1" | tr -d '\000')"
	grep -qF -- "$LIC" <<<"$head" && grep -qF -- "$COPY" <<<"$head"
}

# static_exceptions ROOT: the files ROOT/internal/web/static/README.md lists in its table (the
# vendored htmx, which is minified and cannot carry a header; the README is its licence note).
static_exceptions() {
	local readme="$1/internal/web/static/README.md"
	[ -f "$readme" ] || return 0
	has_header "$readme" || return 0
	sed -n 's/^| `\([^`]*\)`.*/internal\/web\/static\/\1/p' "$readme"
}

# offenders ROOT: prints every tracked file of the git repository ROOT that has no header and no
# exception. Each exception has its reason here; add to it only with a reason a reader can check.
offenders() {
	local root="$1" statics f d
	statics="$(static_exceptions "$root")"
	while IFS= read -r f; do
		case "$f" in
		# Standard text and lock files that no tool lets us annotate: the licence text itself, and
		# two machine-written lockfiles (the npm one carries the licence in package.json's metadata).
		LICENSE | go.sum | e2e/web/package-lock.json) continue ;;
		# The Contributor Covenant is CC BY 4.0, not ours: it carries its own SPDX identifier and
		# the attribution the licence requires, so it cannot have the AGPL line.
		CODE_OF_CONDUCT.md) continue ;;
		# The pull request template is copied verbatim into every PR body, where a licence header
		# would be noise in every description.
		.github/PULL_REQUEST_TEMPLATE.md) continue ;;
		# The public release key must stay byte-identical to `gpg --export --armor` output: sign.sh,
		# rpmkeys and users all consume the file as is, and the fingerprint a user compares is of that
		# export. Exempted by exact path, never by extension: any other .asc is a finding.
		deploy/release/clamfleet-release.asc) continue ;;
		esac
		# Files that bear a Go "Code generated" marker (sqlc output): regenerated by a tool, so a
		# hand-added header would be overwritten and `sqlc diff` would fail.
		if head -n 5 -- "$root/$f" | grep -q '^// Code generated '; then continue; fi
		# Vendored files the static README lists, with their licence.
		if grep -qxF -- "$f" <<<"$statics"; then continue; fi
		# Recorded or golden data (JSON, raw socket bytes, binary) under a testdata directory: covered
		# by the README of that directory, which must itself carry the header.
		case "$f" in
		*/testdata/*)
			d="${f%%/testdata/*}/testdata"
			if [ "$f" != "$d/README.md" ] && [ -f "$root/$d/README.md" ] && has_header "$root/$d/README.md"; then continue; fi
			;;
		esac
		has_header "$root/$f" || echo "$f"
	done < <(git -C "$root" ls-files)
}

fail() { echo "headers_test: FAIL: $*" >&2; exit 1; }

bad="$(offenders "$repo")"
[ -z "$bad" ] || fail "tracked files without both SPDX lines (add them, or list the file with a reason in this script):
$bad"

# The check must be able to fail, and each exception must be an exception and nothing wider.
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
git init -q "$tmp"
cd "$tmp"
hdr() { printf '// %s\n// %s\n' "$LIC" "$COPY"; }
mkdir -p a/testdata b/testdata c/testdata internal/web/static sqlcdb
hdr >good.go
echo 'package x' >bad.go                                     # no header: must be reported
{ for _ in $(seq 20); do echo '// filler'; done; hdr; } >late.go # header below line 15: reported
{ printf '// %s\n' "$LIC"; } >half.go                        # one of the two lines: reported
printf '// Code generated by sqlc. DO NOT EDIT.\npackage x\n' >sqlcdb/q.go
printf '<!--\n%s\n%s\n-->\n' "$LIC" "$COPY" >a/testdata/README.md
echo '{}' >a/testdata/x.json                                 # covered by a/testdata/README.md
echo '{}' >b/testdata/x.json                                 # b has no README: reported
echo 'no header here' >c/testdata/README.md
echo '{}' >c/testdata/x.json                                 # README without header covers nothing: reported
printf '<!--\n%s\n%s\n-->\n| File |\n| `vendor.js` | x |\n' "$LIC" "$COPY" >internal/web/static/README.md
echo 'minified' >internal/web/static/vendor.js              # listed in the static README: exempt
echo 'minified' >internal/web/static/other.js               # not listed: reported
echo 'text' >LICENSE
mkdir -p deploy/release
echo 'armored' >deploy/release/clamfleet-release.asc          # the published key, by exact path: exempt
echo 'armored' >deploy/release/other.asc                     # another .asc: reported
git add -A >/dev/null
got="$(offenders "$tmp" | LC_ALL=C sort | tr '\n' ' ')"
want="b/testdata/x.json bad.go c/testdata/README.md c/testdata/x.json deploy/release/other.asc half.go internal/web/static/other.js late.go "
[ "$got" = "$want" ] || fail "self-test: offenders were '$got', wanted '$want'"
echo "headers_test: ok"
